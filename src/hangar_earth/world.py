"""Write a Gazebo world for an area: heightmap, textures, metadata and credits."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from PIL import Image

from . import __version__
from .geo import Area

NAME_RE = re.compile(r"^[A-Za-z0-9_-]+$")


@dataclass
class Terrain:
    area: Area
    heights: np.ndarray  # metres above sea level, n x n, row 0 = north

    @property
    def zmin(self) -> float:
        return float(self.heights.min())

    @property
    def relief(self) -> float:
        return max(float(self.heights.max()) - self.zmin, 0.1)

    def height_at(self, east: float, north: float) -> float:
        """Ground height above the world origin (= zmin) at local metres."""
        n = self.heights.shape[0]
        col = (east + self.area.half) / self.area.size * (n - 1)
        row = (self.area.half - north) / self.area.size * (n - 1)
        r = int(round(min(max(row, 0), n - 1)))
        c = int(round(min(max(col, 0), n - 1)))
        return float(self.heights[r, c]) - self.zmin


def heightmap_png(t: Terrain) -> Image.Image:
    """16-bit greyscale: 0 = lowest point, 65535 = highest."""
    scaled = (t.heights - t.zmin) / t.relief * 65535
    return Image.fromarray(np.round(scaled).astype(np.uint16))


def normal_map(t: Terrain, pixels: int) -> Image.Image:
    """Surface normals from the terrain, so the sun lights the slopes."""
    n = t.heights.shape[0]
    cell = t.area.size / (n - 1)
    gy, gx = np.gradient(t.heights, cell)  # rows run south: the north slope is -gy
    nx, ny, nz = -gx, gy, np.ones_like(t.heights)
    length = np.sqrt(nx ** 2 + ny ** 2 + nz ** 2)
    rgb = np.stack([(nx / length + 1) / 2, (ny / length + 1) / 2, (nz / length + 1) / 2], axis=-1)
    return Image.fromarray((rgb * 255).astype(np.uint8)).resize((pixels, pixels), Image.BILINEAR)


