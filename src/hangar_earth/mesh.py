"""Extrude building footprints into one Wavefront OBJ mesh (walls + flat roofs).

One mesh for all buildings keeps Gazebo fast: a city block of thousands of
buildings is one visual and one collision instead of thousands."""

from __future__ import annotations

from collections.abc import Callable, Sequence
from pathlib import Path

from .osm import Building

Point = tuple[float, float]

WALLS = {  # name: diffuse RGB
    "wall_light": (0.82, 0.79, 0.73),
    "wall_sand": (0.78, 0.70, 0.58),
    "wall_grey": (0.66, 0.67, 0.69),
    "wall_brick": (0.70, 0.52, 0.44),
}
ROOF = ("roof", (0.42, 0.40, 0.40))


def signed_area(ring: Sequence[Point]) -> float:
    return 0.5 * sum(ring[i][0] * ring[(i + 1) % len(ring)][1] - ring[(i + 1) % len(ring)][0] * ring[i][1]
                     for i in range(len(ring)))


def _cross(o: Point, a: Point, b: Point) -> float:
    return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])


def _inside(p: Point, a: Point, b: Point, c: Point) -> bool:
    return _cross(a, b, p) >= 0 and _cross(b, c, p) >= 0 and _cross(c, a, p) >= 0


def triangulate(ring: Sequence[Point]) -> list[tuple[int, int, int]]:
    """Ear clipping for a simple counter-clockwise polygon. Returns index triples."""
    idx = list(range(len(ring)))
    tris: list[tuple[int, int, int]] = []
    guard = 0
    while len(idx) > 3 and guard < 10 * len(ring) * len(ring):
        guard += 1
        n = len(idx)
        for k in range(n):
            i0, i1, i2 = idx[(k - 1) % n], idx[k], idx[(k + 1) % n]
            a, b, c = ring[i0], ring[i1], ring[i2]
            if _cross(a, b, c) <= 1e-9:
                continue  # reflex or degenerate corner
            if any(_inside(ring[j], a, b, c) for j in idx if j not in (i0, i1, i2)):
                continue
            tris.append((i0, i1, i2))
            del idx[k]
            break
        else:
            break  # self-intersecting outline: fan the rest
    for k in range(1, len(idx) - 1):
        tris.append((idx[0], idx[k], idx[k + 1]))
    return tris


def write_obj(buildings: list[Building], ground: Callable[[float, float], float], obj: Path) -> int:
    """Write obj (+ .mtl next to it). ground(x, y) is the terrain height in world z.
    Returns the number of triangles."""
    mtl = obj.with_suffix(".mtl")
    mtl.write_text("".join(
        f"newmtl {name}\nKa {r * 0.6:.3f} {g * 0.6:.3f} {b * 0.6:.3f}\nKd {r:.3f} {g:.3f} {b:.3f}\n"
        f"Ks 0.05 0.05 0.05\nNs 10\nd 1\nillum 2\n\n"
        for name, (r, g, b) in [*WALLS.items(), ROOF]
    ), encoding="ascii")
    verts: list[str] = []
    normals: list[str] = ["vn 0 0 1"]
    faces: dict[str, list[str]] = {name: [] for name in [*WALLS, ROOF[0]]}
    wall_names = list(WALLS)
    triangles = 0
    for b in buildings:
        ring = list(b.outline)
        if signed_area(ring) < 0:
            ring.reverse()
        if abs(signed_area(ring)) < 1.0:
            continue  # slivers
        base = min(ground(x, y) for x, y in ring) - 0.5  # sink a little on slopes
        top = base + 0.5 + b.height
        first = len(verts) + 1
        for x, y in ring:
            verts.append(f"v {x:.2f} {y:.2f} {base:.2f}")
            verts.append(f"v {x:.2f} {y:.2f} {top:.2f}")
        n = len(ring)
        wall = wall_names[b.osm_id % len(wall_names)]
        for i in range(n):
            j = (i + 1) % n
            (x0, y0), (x1, y1) = ring[i], ring[j]
            length = ((x1 - x0) ** 2 + (y1 - y0) ** 2) ** 0.5 or 1.0
            normals.append(f"vn {(y1 - y0) / length:.4f} {-(x1 - x0) / length:.4f} 0")  # outward for CCW
            vn = len(normals)
            b0, t0, b1, t1 = first + 2 * i, first + 2 * i + 1, first + 2 * j, first + 2 * j + 1
            faces[wall].append(f"f {b0}//{vn} {b1}//{vn} {t1}//{vn}")
            faces[wall].append(f"f {b0}//{vn} {t1}//{vn} {t0}//{vn}")
            triangles += 2
        for i0, i1, i2 in triangulate(ring):
            faces[ROOF[0]].append(f"f {first + 2 * i0 + 1}//1 {first + 2 * i1 + 1}//1 {first + 2 * i2 + 1}//1")
            triangles += 1
    lines = [f"# {len(buildings)} buildings, generated by hangar-earth", f"mtllib {mtl.name}", *verts, *normals]
    for name, fs in faces.items():
        if fs:
            lines += [f"usemtl {name}", *fs]
    obj.write_text("\n".join(lines) + "\n", encoding="ascii")
    return triangles
